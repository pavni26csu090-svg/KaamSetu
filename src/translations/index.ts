/**
 * Helper translation lookup function supporting nested keys (e.g. 'hero.headline')
 * with parameter interpolation and fallback.
 */
export function translate(
  lang: 'en' | 'hi',
  key: string,
  params?: Record<string, string | number>
): string {
  const dict = translations[lang] || translations.en;
  const parts = key.split('.');
  let current: any = dict;

  for (const part of parts) {
    if (current && typeof current === 'object' && part in current) {
      current = current[part];
    } else {
      current = undefined;
      break;
    }
  }

  // Fallback to English if missing in Hindi
  if (current === undefined && lang !== 'en') {
    let fallbackCurrent: any = translations.en;
    for (const part of parts) {
      if (fallbackCurrent && typeof fallbackCurrent === 'object' && part in fallbackCurrent) {
        fallbackCurrent = fallbackCurrent[part];
      } else {
        fallbackCurrent = undefined;
        break;
      }
    }
    current = fallbackCurrent;
  }

  if (current === undefined || typeof current !== 'string') {
    if (process.env.NODE_ENV !== 'production') {
      console.warn(`[KaamSetu i18n] Missing translation for key: "${key}" in language "${lang}"`);
    }
    return key;
  }

  if (params) {
    let result = current;
    for (const [pKey, pVal] of Object.entries(params)) {
      result = result.replace(new RegExp(`\\{${pKey}\\}`, 'g'), String(pVal));
    }
    return result;
  }

  return current;
}
